const dictionaries: Record<ResolvedAppLocale, Record<string, string>> = {
  en: {},
  zh_CN: zhCN,
  zh_TW: zhTW
};

const browserLanguages = () =>
  typeof navigator === "undefined"
    ? ["en"]
    : navigator.languages?.length
      ? navigator.languages
      : [navigator.language];

export const resolveAppLocale = (
  preference: AppLocale,
  languages: readonly string[] = browserLanguages()
): ResolvedAppLocale => {
  if (preference !== "system") {
    return preference;
  }
  const language = languages.find(Boolean)?.replace("_", "-").toLowerCase() ?? "en";
  if (!language.startsWith("zh")) {
    return "en";
  }
  return /(?:hant|tw|hk|mo)(?:-|$)/i.test(language) ? "zh_TW" : "zh_CN";
};

export const localeTag = (locale: ResolvedAppLocale) =>
  locale === "zh_CN" ? "zh-CN" : locale === "zh_TW" ? "zh-TW" : "en-US";

export const translate = (
  locale: ResolvedAppLocale,
  message: string,
  values: TranslationValues = {}
) => {
  const template = dictionaries[locale][message] ?? message;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, key: string) =>
    key in values ? String(values[key]) : `{{${key}}}`
  );
};

interface I18nContextValue {
  locale: ResolvedAppLocale;
  localeTag: string;
  t(message: string, values?: TranslationValues): string;
  formatDate(value: string | number | Date): string;
  formatNumber(value: number): string;
}

const defaultI18nContext: I18nContextValue = {
  locale: "en",
  localeTag: "en-US",
  t: (message, values) => translate("en", message, values),
  formatDate: (input) => new Date(input).toLocaleString("en-US"),
  formatNumber: (input) => input.toLocaleString("en-US")
};

const I18nContext = createContext<I18nContextValue>(defaultI18nContext);

export const I18nProvider = ({
  preference,
  children
}: {
  preference: AppLocale;
  children: ReactNode;
}) => {
  const locale = resolveAppLocale(preference);
  const tag = localeTag(locale);
  const t = useCallback(
    (message: string, values?: TranslationValues) => translate(locale, message, values),
    [locale]
  );
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      localeTag: tag,
      t,
      formatDate: (input) => new Date(input).toLocaleString(tag),
      formatNumber: (input) => input.toLocaleString(tag)
    }),
    [locale, t, tag]
  );

  useEffect(() => {
    document.documentElement.lang = tag;
  }, [tag]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  return useContext(I18nContext);
};
